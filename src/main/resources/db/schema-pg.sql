-- ============================================================================
-- JavaVision 业务表结构（PostgreSQL 12+）
--
-- 命名与类型遵循《阿里巴巴 Java 开发手册》建表规约：
--   1. 表名、字段名全小写、只用字母数字下划线，不使用复数、不使用保留字
--   2. 表名 = 业务名称_表的作用，库名与应用名一致（java_vision）
--   3. 必备三字段 id / create_time / update_time，id 为 bigint 自增主键
--   4. 0/1 标志位字段 is_ 前缀（1 是、0 否），POJO 侧不加 is 前缀
--   5. 索引前缀 pk_ 主键 / uk_ 唯一 / idx_ 普通
--   6. 定长字符串用 char（md5 固定 32 位）
--   7. 超长文本（人脸特征向量）独立成表，避免拖慢主表
--
-- 与 MySQL 规约的差异（受 PostgreSQL 语法约束，均为等价实现）：
--   - PG 无 unsigned / tinyint，0/1 标志位统一用 smallint（0 未删除 / 1 已删除）
--   - PG 索引名在 schema 内全局唯一，故索引名需带表名限定，
--     形如 uk_face_person_person_id，而非 MySQL 中可复用的 uk_字段名
--   - PG 无 datetime，用 timestamp（不带时区，与 LocalDateTime 对应）
--   - PG 自增用 identity 列，等价于 MySQL 的 auto_increment
--
-- 本脚本幂等，随 Spring 启动执行（spring.sql.init.mode=always）。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 人脸库人员信息
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vision_face_person
(
    id          bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    person_id   varchar(64) NOT NULL,
    person_name varchar(128),
    image_url   varchar(1024),
    feature_dim integer,
    is_deleted  smallint    NOT NULL DEFAULT 0,
    create_time timestamp   NOT NULL DEFAULT now(),
    update_time timestamp   NOT NULL DEFAULT now(),
    CONSTRAINT pk_face_person PRIMARY KEY (id)
);

COMMENT ON TABLE vision_face_person IS '人脸库人员信息';
COMMENT ON COLUMN vision_face_person.id IS '主键，自增';
COMMENT ON COLUMN vision_face_person.person_id IS '人员业务编号，调用方传入，未删除记录内唯一';
COMMENT ON COLUMN vision_face_person.person_name IS '人员姓名';
COMMENT ON COLUMN vision_face_person.image_url IS '人脸图片地址（MinIO URL 或本地绝对路径）';
COMMENT ON COLUMN vision_face_person.feature_dim IS '人脸特征维度，冗余自特征表便于列表展示';
COMMENT ON COLUMN vision_face_person.is_deleted IS '是否删除：1 已删除，0 未删除';
COMMENT ON COLUMN vision_face_person.create_time IS '创建时间';
COMMENT ON COLUMN vision_face_person.update_time IS '更新时间';

-- 逻辑删除下 person_id 仅对未删除记录唯一，历史记录可保留审计。
-- 该部分唯一索引由 db/SchemaMigrator 在启动时创建：历史库 is_deleted 仍是 boolean，
-- 在本脚本里直接写 WHERE is_deleted = 0 会在解析阶段报类型不匹配，故统一交给迁移器。

CREATE INDEX IF NOT EXISTS idx_face_person_person_name
    ON vision_face_person (person_name);

CREATE INDEX IF NOT EXISTS idx_face_person_create_time
    ON vision_face_person (create_time DESC);

-- ----------------------------------------------------------------------------
-- 人脸特征向量（大文本独立成表，1:1 对应 vision_face_person）
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vision_face_feature
(
    id          bigint    NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    face_id     bigint    NOT NULL,
    feature     text      NOT NULL,
    feature_dim integer   NOT NULL,
    create_time timestamp NOT NULL DEFAULT now(),
    update_time timestamp NOT NULL DEFAULT now(),
    CONSTRAINT pk_face_feature PRIMARY KEY (id),
    CONSTRAINT fk_face_feature_face_id FOREIGN KEY (face_id)
        REFERENCES vision_face_person (id) ON DELETE CASCADE
);

COMMENT ON TABLE vision_face_feature IS '人脸特征向量，1:1 对应 vision_face_person';
COMMENT ON COLUMN vision_face_feature.id IS '主键，自增';
COMMENT ON COLUMN vision_face_feature.face_id IS '所属人员，关联 vision_face_person.id';
COMMENT ON COLUMN vision_face_feature.feature IS '特征向量，JSON 数组文本（如 [0.12,-0.03,...]）';
COMMENT ON COLUMN vision_face_feature.feature_dim IS '特征维度';
COMMENT ON COLUMN vision_face_feature.create_time IS '创建时间';
COMMENT ON COLUMN vision_face_feature.update_time IS '更新时间';

CREATE UNIQUE INDEX IF NOT EXISTS uk_face_feature_face_id
    ON vision_face_feature (face_id);

-- ----------------------------------------------------------------------------
-- 图库元数据（向量本身在 vectorex / milvus / es）
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vision_image
(
    id          bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    image_id    varchar(64) NOT NULL,
    url         varchar(1024),
    md5         char(32),
    vector_dim  integer,
    index_type  varchar(16),
    is_deleted  smallint    NOT NULL DEFAULT 0,
    create_time timestamp   NOT NULL DEFAULT now(),
    update_time timestamp   NOT NULL DEFAULT now(),
    CONSTRAINT pk_image PRIMARY KEY (id)
);

COMMENT ON TABLE vision_image IS '图库图片元数据，向量存于向量库';
COMMENT ON COLUMN vision_image.id IS '主键，自增';
COMMENT ON COLUMN vision_image.image_id IS '图片业务编号，调用方传入，未删除记录内唯一';
COMMENT ON COLUMN vision_image.url IS '原图地址（MinIO URL 或本地绝对路径）';
COMMENT ON COLUMN vision_image.md5 IS '原图内容摘要，定长 32 位，用于去重与向量缓存命中';
COMMENT ON COLUMN vision_image.vector_dim IS '图片特征维度';
COMMENT ON COLUMN vision_image.index_type IS '向量库类型：vectorex / milvus / es';
COMMENT ON COLUMN vision_image.is_deleted IS '是否删除：1 已删除，0 未删除';
COMMENT ON COLUMN vision_image.create_time IS '创建时间';
COMMENT ON COLUMN vision_image.update_time IS '更新时间';

-- 未删除记录内 image_id 唯一，同 uk_face_person_person_id 由 db/SchemaMigrator 创建

CREATE INDEX IF NOT EXISTS idx_image_md5
    ON vision_image (md5);

CREATE INDEX IF NOT EXISTS idx_image_create_time
    ON vision_image (create_time DESC);
